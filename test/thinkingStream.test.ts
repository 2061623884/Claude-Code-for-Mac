import { describe, expect, it } from 'vitest'
import { Transcript } from '../src/main/transcript'
import { TurnActivity } from '../src/main/live/TurnActivity'
const stream = (t: Transcript, event: unknown, parent: string | null = null): void => t.apply({ type: 'stream_event', event, parent_tool_use_id: parent })
const start = (t: Transcript, id: string, parent: string | null = null): void => stream(t, { type: 'message_start', message: { id } }, parent)
const thinking = (t: Transcript, index = 0, parent: string | null = null): void => stream(t, { type: 'content_block_start', index, content_block: { type: 'thinking', thinking: '' } }, parent)
const delta = (t: Transcript, text: string, index = 0, parent: string | null = null): void => stream(t, { type: 'content_block_delta', index, delta: { type: 'thinking_delta', thinking: text } }, parent)
const final = (t: Transcript, id: string, content: unknown[], uuid: string, parent: string | null = null): void => t.apply({ type: 'assistant', uuid, parent_tool_use_id: parent, message: { id, content } })
describe('thinking stream reconciliation', () => {
  it('keeps interleaved main and child streams separate, even for identical message IDs', () => {
    const t = new Transcript()
    start(t, 'm'); thinking(t)
    start(t, 'm', 'agent'); thinking(t, 0, 'agent')
    delta(t, '主会话'); delta(t, '子 Agent', 0, 'agent'); delta(t, '摘要')
    expect(t.messages).toHaveLength(2)
    expect(t.messages[0].blocks).toEqual([{ kind: 'thinking', text: '主会话摘要' }])
    expect(t.messages[1].blocks).toEqual([{ kind: 'thinking', text: '子 Agent' }])
    expect(t.messages[0].id).not.toBe(t.messages[1].id)
  })
  it('reconciles per-block finals and full snapshots without duplicates or loss of text', () => {
    const t = new Transcript()
    start(t, 'm'); thinking(t); delta(t, '第一段')
    final(t, 'm', [{ type: 'thinking', thinking: '' }], 'part-1')
    stream(t, { type: 'content_block_start', index: 1, content_block: { type: 'text', text: '' } })
    stream(t, { type: 'content_block_delta', index: 1, delta: { type: 'text_delta', text: '回复' } })
    final(t, 'm', [{ type: 'text', text: '回复' }], 'part-2')
    final(t, 'm', [{ type: 'thinking', thinking: '' }], 'part-1')
    final(t, 'm', [{ type: 'thinking', thinking: '' }, { type: 'text', text: '回复' }], 'all')
    final(t, 'm', [{ type: 'thinking', thinking: '' }, { type: 'text', text: '回复' }], 'all')
    expect(t.messages[0].blocks).toEqual([{ kind: 'thinking', text: '第一段' }, { kind: 'text', text: '回复' }])
  })
  it('routes delayed single-block finals to their original unconfirmed slots', () => {
    const t = new Transcript()
    start(t, 'm'); thinking(t); delta(t, '一')
    thinking(t, 1); delta(t, '二', 1)
    final(t, 'm', [{ type: 'thinking', thinking: '一' }], 'one')
    final(t, 'm', [{ type: 'thinking', thinking: '二' }], 'two')
    stream(t, { type: 'message_stop' })
    delta(t, '不应追加', 1)
    expect(t.messages[0].blocks).toEqual([{ kind: 'thinking', text: '一' }, { kind: 'thinking', text: '二' }])
  })
  it('keeps historical split blocks and repeated tool finals with results intact', () => {
    const t = new Transcript()
    final(t, 'm', [{ type: 'thinking', thinking: '历史摘要' }], 'one')
    const tool = { type: 'tool_use', id: 'read', name: 'Read', input: {} }
    final(t, 'm', [tool], 'two')
    t.apply({ type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 'read', content: 'ok' }] } })
    final(t, 'm', [tool], 'two')
    expect(t.messages[0].blocks).toHaveLength(2)
    expect(t.messages[0].blocks[1]).toMatchObject({ result: { text: 'ok' } })
  })
  it('does not manufacture thinking text from signatures or token estimates', () => {
    const t = new Transcript()
    start(t, 'm'); thinking(t)
    stream(t, { type: 'content_block_delta', index: 0, delta: { type: 'signature_delta', signature: 'opaque' } })
    stream(t, { type: 'content_block_delta', index: 0, delta: { type: 'thinking_delta', estimated_tokens: 100 } })
    t.apply({ type: 'system', subtype: 'thinking_tokens', estimated_tokens: 100 })
    expect(t.messages[0].blocks).toEqual([{ kind: 'thinking', text: '' }])
  })
})
describe('current work activity', () => {
  it('tracks root thinking, tool work and text, without being overwritten by child messages', () => {
    const activity = new TurnActivity(); activity.start()
    activity.apply({ type: 'stream_event', event: { type: 'content_block_start', content_block: { type: 'thinking' } } })
    expect(activity.snapshot().phase).toBe('thinking')
    activity.apply({ type: 'assistant', parent_tool_use_id: 'child', message: { content: [{ type: 'text', text: 'child text' }] } })
    expect(activity.snapshot().phase).toBe('thinking')
    activity.apply({ type: 'assistant', message: { content: [{ type: 'tool_use', id: 'read', name: 'Read' }] } })
    expect(activity.snapshot()).toMatchObject({ phase: 'tool', toolName: 'Read' })
    activity.apply({ type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 'read' }] } })
    expect(activity.snapshot().phase).toBe('working')
    activity.apply({ type: 'stream_event', event: { type: 'content_block_delta', delta: { type: 'text_delta', text: '回答' } } })
    expect(activity.snapshot().phase).toBe('responding')
    activity.finish(); expect(activity.snapshot().phase).toBe('idle')
  })
  it('continues to report another running tool after one finishes and ignores events while stopping', () => {
    const activity = new TurnActivity(); activity.start()
    for (const id of ['a', 'b']) activity.apply({ type: 'tool_progress', tool_use_id: id, tool_name: 'Bash' })
    activity.apply({ type: 'user', message: { content: [{ type: 'tool_result', tool_use_id: 'b' }] } })
    expect(activity.snapshot()).toMatchObject({ phase: 'tool', toolId: 'a' })
    activity.stop(); activity.apply({ type: 'system', subtype: 'thinking_tokens' })
    expect(activity.snapshot().phase).toBe('stopping')
    const revision = activity.snapshot().revision
    activity.finish(); expect(activity.snapshot().revision).toBeGreaterThan(revision)
    const replacement = new TurnActivity(); replacement.start()
    expect(replacement.snapshot().revision).toBeGreaterThan(activity.snapshot().revision)
  })
})

it('preserves distinct historical blocks even when their text is identical', () => {
  const t = new Transcript()
  final(t, 'm', [{ type: 'thinking', thinking: '同样的摘要' }], 'first')
  final(t, 'm', [{ type: 'thinking', thinking: '同样的摘要' }], 'second')
  final(t, 'm', [{ type: 'thinking', thinking: '同样的摘要' }], 'second')
  expect(t.messages[0].blocks).toHaveLength(2)
})
